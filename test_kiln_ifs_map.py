#!/usr/bin/env python3
"""Tests for kiln_ifs_map.py without OrcaSlicer.

usage: python3 test_kiln_ifs_map.py [PRINTER_URL]
With PRINTER_URL (e.g. http://<printer-ip>) the printer's live slots are
also read (read-only query) and a sample file is mapped against them.
"""
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kiln_ifs_map as k  # noqa: E402

failed = 0


def check(name, ok, detail=""):
    global failed
    print(("ok   " if ok else "FAIL ") + name + ("" if ok else f": {detail}"))
    failed += not ok


GCODE = """; HEADER_BLOCK_START
; generated by OrcaSlicer
; HEADER_BLOCK_END
PRINT_START BED=60 EXTRUDER=220 TOOL=0
G1 X10 Y10
T2
G1 X20
T0
; filament used [mm] = 120.5, 0.00, 33.1, 0.00
; filament_type = PLA;PLA;PETG;PLA
; filament_colour = #FF0000;#00FF00;#FFFFFF;#000000
"""

# printer: slot 1 white PETG, slot 2 empty, slot 3 red-ish PLA, slot 4 black PLA
SLOTS = {1: ("PETG", (250, 250, 250)), 2: ("PLA", (0, 255, 0)),
         3: ("PLA", (230, 10, 10)), 4: ("PLA", (0, 0, 0))}
PRESENT = {1, 3, 4}


def run(text, cfg, slots=SLOTS, present=PRESENT, fail=None):
    def q(url, timeout):
        if fail:
            raise fail
        return slots, present
    fd, p = tempfile.mkstemp(suffix=".gcode")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    ok, msg = k.process(p, dict(k.DEFAULTS, **cfg), None, q)
    out = open(p).read()
    os.unlink(p)
    return ok, msg, out


lines = GCODE.splitlines(True)
check("used tools from usage, T and TOOL=", k.used_tools(lines) == [0, 2],
      k.used_tools(lines))
check("filament types", k.config_list(lines, "filament_type")[2] == "PETG")
check("family", k.family("PLA-CF") == "PLA" and k.family("SILK") == "PLA")
check("rank", [k.material_rank("PLA", x) for x in ("PLA", "PLA-CF", "", "PETG")]
      == [0, 1, 2, 3])

ok, msg, out = run(GCODE, {"printer_url": "http://p"})
check("maps by material and colour", ok and "IFS_MAP_TOOL TOOL=0 SLOT=3" in out
      and "IFS_MAP_TOOL TOOL=2 SLOT=1" in out, msg + "\n" + out)
check("block after the first line", out.splitlines()[1].startswith(k.MARK + " start"))

# idempotent: a second run replaces its own block
fd, p = tempfile.mkstemp(suffix=".gcode")
with os.fdopen(fd, "w") as f:
    f.write(out)
k.process(p, dict(k.DEFAULTS, printer_url="http://p"), None,
          lambda u, t: (SLOTS, PRESENT))
again = open(p).read()
os.unlink(p)
check("second run: one block", again.count(k.MARK + " start") == 1
      and again.count("IFS_MAP_TOOL TOOL=0") == 1)

# empty slot 2 is skipped although it has the exact colour of T1
g1 = GCODE.replace("T2\n", "T1\n").replace("120.5, 0.00, 33.1", "0, 50, 0")
ok, msg, out = run(g1.replace("TOOL=0", "TOOL=1"), {"printer_url": "http://p"})
check("slot without filament never chosen", "SLOT=2" not in out, out)

# material in no slot
gabs = GCODE.replace("PLA;PLA;PETG;PLA", "ABS;PLA;PETG;PLA")
ok, msg, out = run(gabs, {"printer_url": "http://p"})
check("mismatch stops the export", not ok and "T0" in msg and "ABS" in msg, msg)
ok, msg, out = run(gabs, {"printer_url": "http://p", "on_mismatch": "keep"})
check("mismatch keep: others mapped", ok and "IFS_MAP_TOOL TOOL=0" not in out
      and "IFS_MAP_TOOL TOOL=2 SLOT=1" in out, out)

# offline
ok, msg, out = run(GCODE, {"printer_url": "http://p"}, fail=OSError("down"))
check("offline: unchanged", ok and out == GCODE, msg)
ok, msg, out = run(GCODE, {"printer_url": "http://p", "if_offline": "error"},
                   fail=OSError("down"))
check("offline error: stops", not ok, msg)
ok, msg, out = run(GCODE, {})
check("no url: unchanged", ok and out == GCODE, msg)

# unknown slot types (no IFS_SET_MATERIAL yet): colour decides
ok, msg, out = run(GCODE, {"printer_url": "http://p"},
                   slots={s: ("", c) for s, (t, c) in SLOTS.items()})
check("untyped slots: by colour", ok and "IFS_MAP_TOOL TOOL=0 SLOT=3" in out, out)

# Inside OrcaSlicer: a stand-in for the orca module (API of OrcaSlicer's
# plugin system, src/slic3r/plugin/PythonPluginBridge.cpp)
import types  # noqa: E402
import importlib  # noqa: E402
orca = types.ModuleType("orca")
class _Res:
    def __init__(self, status, message):
        self.status, self.message = status, message
orca.ExecutionResult = types.SimpleNamespace(
    success=lambda m="": _Res("Success", m),
    failure=lambda st, m: _Res(st, m))
orca.PluginResult = types.SimpleNamespace(RecoverableError="RecoverableError")
orca.slicing = types.SimpleNamespace(
    Step=types.SimpleNamespace(psGCodePostProcess="pp", posSlice="slice"),
    SlicingPipelineCapabilityBase=type("Base", (), {
        "get_config": lambda self: '{"printer_url": "http://p"}'}))
orca.base = type("PluginBase", (), {})
registered = []
orca.plugin = lambda cls: cls
orca.register_capability = registered.append
sys.modules["orca"] = orca
kp = importlib.reload(k)
kp.KilnIfsToolMapPackage().register_capabilities()
cap = registered[0]()
real_query = kp.query_printer
kp.query_printer = lambda url, timeout: (SLOTS, PRESENT)
fd, p = tempfile.mkstemp(suffix=".gcode")
with os.fdopen(fd, "w") as f:
    f.write(GCODE)
r1 = cap.execute(types.SimpleNamespace(step="slice", gcode_path=""))
ctx = types.SimpleNamespace(step="pp", gcode_path=p, host="OctoPrint",
                            config_value=lambda key: None)
r2 = cap.execute(ctx)
check("orca: registers one capability", len(registered) == 1
      and cap.get_name() == "Kiln IFS Tool Map")
check("orca: geometry steps untouched", r1.status == "Success")
check("orca: post-process maps", r2.status == "Success"
      and "SLOT=3" in open(p).read(), r2.message)
with open(p, "w") as f:
    f.write(GCODE.replace("PETG", "ASA"))
r3 = cap.execute(ctx)
check("orca: mismatch -> RecoverableError", r3.status == "RecoverableError", r3.message)
os.unlink(p)
del sys.modules["orca"]
kp.query_printer = real_query

if len(sys.argv) > 1:
    slots, present = k.query_printer(sys.argv[1], 5)
    print("printer slots:", {s: k.describe(*v) for s, v in slots.items()},
          "with filament:", present)
    ok, msg, out = run(GCODE, {"printer_url": sys.argv[1], "on_mismatch": "keep"},
                       slots=slots, present=present)
    print("sample file:", msg)
    check("live printer query", ok, msg)

print("FAILED" if failed else "all OK")
sys.exit(1 if failed else 0)
